"""
html2typst.py — port the manuscript from the HTML template to Typst.

    python3 html2typst.py paper_national_v3.html paper_national.typ

Written as a converter rather than a retype so the state editions inherit it and
so the port is reversible: the HTML stays the source of record until the Typst
output has been compared against it.

The point of the move is float placement. A column figure becomes a float scoped
to its column and a spanning figure a float scoped to the page, and the engine
decides where they sit instead of the author guessing and sweeping heights.
"""
