# dc_provenance.py — every DC figure, where it came from, and whether
# anybody has actually checked it.
#
# WHY THIS EXISTS. The District panels are going into a demo. Both of them
# carry a mixture of measured figures, figures we derived, figures we assumed,
# and figures that are not there at all, and from the outside those look
# identical: they are all numbers on a plate. This generates the record that
# tells them apart, from the ledgers themselves rather than from a document
# somebody maintains by hand.
#
# NOTHING HERE IS BLESSED. "Signed" in this project means a person opened the
# source and agreed with the number (signatures.py). The signature register
# covers the national panels. It contains no District entry, so every DC
# figure is UNVERIFIED by the project's own test — including the ones that are
# measured and correct. Measured is a claim about where a number came from;
# verified is a claim that somebody looked. They are different, and the demo
# needs to say the second one is missing.
#
# Run: python3 dc_provenance.py           prints the report
#      python3 dc_provenance.py --write   writes DC_PROVENANCE.md

import sys

import ledger as LD

STATUS_ORDER = {LD.MEASURED: 0, LD.DERIVED: 1, LD.MODELLED: 2, LD.ABSENT: 3}

PANELS = [
    ("DC FY2024 as-is", "ledger_dc_2024", "build", {"legacy_mix": False}),
    ("DC FY2030 to-be (DRAFT)", "ledger_dc_2030", "ledger", {}),
]


def _load():
    import importlib
    out = []
    for label, mod, fn, kw in PANELS:
        m = importlib.import_module(mod)
        out.append((label, getattr(m, fn)(**kw)))
    return out


def rows(L):
    """One row per figure, in status order then key order."""
    out = []
    for key, f in sorted(L.figures().items()):
        out.append({
            "key": key,
            "value": "ABSENT" if f.is_absent else f"{float(f.value):,.4f}",
            "status": f.status,
            "basis": f.basis or "",
            "source": f.source or "",
            "vintage": f.vintage or "",
            "verified": f.verified or "",
            "parents": ", ".join(f.parents),
            "note": " ".join((f.note or "").split()),
        })
    out.sort(key=lambda r: (STATUS_ORDER.get(r["status"], 9), r["key"]))
    return out


def assumptions(L):
    """Every figure that is an assumption rather than an observation.

    MODELLED is the project's word for "we chose this". A DERIVED figure is
    only as good as its parents, so a derivation standing on a modelled parent
    is an assumption wearing a derivation's clothes, and it is listed here too
    with the parent named.
    """
    figs = L.figures()
    out = []
    for key, f in sorted(figs.items()):
        if f.is_absent:
            continue
        if f.status == LD.MODELLED:
            out.append((key, "chosen", " ".join((f.note or "").split())))
        elif f.status == LD.DERIVED:
            bad = [p for p in f.parents
                   if figs.get(p.replace("anchor.", "anchor.")) is not None
                   and figs[p].status == LD.MODELLED] if f.parents else []
            if bad:
                out.append((key, "derived on a chosen parent: " + ", ".join(bad),
                            " ".join((f.note or "").split())))
    return out


def absences(L):
    return [(k, " ".join((f.note or "").split()))
            for k, f in sorted(L.figures().items()) if f.is_absent]


def report():
    L = []
    A = [
        "# DC provenance — every figure, and whether anyone has checked it",
        "",
        "Generated by `dc_provenance.py` from the ledgers. Do not hand-edit: "
        "re-run it.",
        "",
        "## Read this before the demo",
        "",
        "**No District figure in this project is signed.** In this project "
        "*signed* means a named person opened the source and agreed with the "
        "number, and the register that records it (`signatures.py`) has no DC "
        "entry at all. Every figure below is therefore UNVERIFIED, including "
        "the ones that are measured, correct and uncontroversial. Measured "
        "says where a number came from. Verified says somebody looked. The "
        "second one has not happened for the District.",
        "",
        "So the stipulation for the demo is not a hedge, it is the literal "
        "state of the data: **the DC figures are not proofread and not "
        "final.** The FY2030 panel is additionally a DRAFT — three of its "
        "seven HR-1 lanes carry no District figure at all and are drawn as "
        "absence.",
        "",
        "What the status words mean here:",
        "",
        "| word | meaning |",
        "|---|---|",
        "| MEASURED | read off a published source. Not checked by a person. |",
        "| DERIVED | computed in code from other figures. No stronger than its parents. |",
        "| MODELLED | **we chose it.** An assumption, declared. |",
        "| ABSENT | there is no figure. Drawn as absence, never as zero. |",
        "",
    ]
    for label, lg in _load():
        rs = rows(lg)
        counts = {}
        for r in rs:
            counts[r["status"]] = counts.get(r["status"], 0) + 1
        verified = sum(1 for r in rs if r["verified"])
        A += [f"## {label}", "",
              "  ·  ".join(f"**{counts.get(k,0)}** {k}"
                           for k in (LD.MEASURED, LD.DERIVED,
                                     LD.MODELLED, LD.ABSENT)),
              "", f"**{verified} of {len(rs)} figures verified by a person.**",
              ""]

        ass = assumptions(lg)
        A += ["### What we chose rather than observed", ""]
        if ass:
            A += ["| figure | why it is an assumption | what was assumed |",
                  "|---|---|---|"]
            A += [f"| `{k}` | {why} | {note} |" for k, why, note in ass]
        else:
            A += ["None.", ""]
        A += [""]

        abs_ = absences(lg)
        A += ["### What is not there", ""]
        if abs_:
            A += ["| figure | the ledger's own words |", "|---|---|"]
            A += [f"| `{k}` | {note} |" for k, note in abs_]
        else:
            A += ["Nothing absent.", ""]
        A += [""]

        A += ["### Every figure", "",
              "| figure | value | status | verified | source | note |",
              "|---|---|---|---|---|---|"]
        for r in rs:
            src = r["source"] or (f"derived from {r['parents']}"
                                  if r["parents"] else "—")
            if r["vintage"]:
                src += f" ({r['vintage']})"
            A += [f"| `{r['key']}` | {r['value']} | {r['status']} | "
                  f"{r['verified'] or '**no**'} | {src} | {r['note']} |"]
        A += [""]

    A += ["## What would change this",
          "",
          "A figure becomes verified when someone opens its source, agrees "
          "with the number, and records it in `signatures.py` with the value "
          "they agreed to. Editing a signed figure makes the signature lapse "
          "and fails the build, which is the point of recording the value "
          "rather than just the name.",
          "",
          "Until then the honest line for any audience is the one above: the "
          "District figures are sourced but unproofed, the assumptions are "
          "listed, and the absences are drawn rather than filled.",
          ""]
    return "\n".join(A)


if __name__ == "__main__":
    text = report()
    if "--write" in sys.argv:
        open("DC_PROVENANCE.md", "w").write(text)
        print("wrote DC_PROVENANCE.md")
        for label, lg in _load():
            rs = rows(lg)
            print(f"  {label:<26} {len(rs):>3} figures, "
                  f"{sum(1 for r in rs if r['verified'])} verified, "
                  f"{sum(1 for r in rs if r['status']==LD.MODELLED)} chosen, "
                  f"{sum(1 for r in rs if r['status']==LD.ABSENT)} absent")
    else:
        print(text)
